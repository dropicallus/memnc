#!/usr/bin/env python3
"""Generate per-node NKey identities and the NATS server config (H4).

Creates, for every user (orchestrator + one per node):
  secrets/<user>.nk        -- the NKey seed (mode 0600, NEVER committed)
  secrets/<user>.nk.pub    -- the matching public key

and writes secrets/nats.conf: a NATS server config where each user has its
own NKey entry with deny-by-default permissions derived from the subject map
in memnc/schema.py. Token auth (`--auth`) has no equivalent granularity, which
is exactly the point: "who am I" becomes a transport property instead of a
payload claim.

Usage:
    python scripts/gen_nkeys.py --orchestrator alpha --nodes node-b node-c

Regenerating overwrites secrets/ contents; keep existing seeds by passing
--nodes/--orchestrator unchanged (existing seed files are kept unless
--rotate is given).
"""

from __future__ import annotations

import argparse
import os
import stat
from pathlib import Path

import nkeys
from nacl.signing import SigningKey


def _generate_user_nkey(secrets_dir: Path, user: str, rotate: bool) -> tuple[bytes, str]:
    """Create (or reuse) a seed/public pair for one user; return (seed, pub)."""
    seed_path = secrets_dir / f"{user}.nk"
    pub_path = secrets_dir / f"{user}.nk.pub"
    if seed_path.exists() and pub_path.exists() and not rotate:
        seed = seed_path.read_bytes()
        pub = pub_path.read_text().strip()
        print(f"  keeping existing key for {user} ({pub})")
        return seed, pub
    signing_key = SigningKey.generate()
    seed = nkeys.encode_seed(bytes(signing_key), nkeys.PREFIX_BYTE_USER)
    kp = nkeys.from_seed(seed)
    pub = kp.public_key.decode()
    seed_path.write_bytes(seed)
    os.chmod(seed_path, stat.S_IRUSR | stat.S_IWUSR)  # 0600
    pub_path.write_text(pub + "\n")
    os.chmod(pub_path, stat.S_IRUSR | stat.S_IWUSR)  # 0600
    print(f"  generated key for {user} ({pub})")
    return seed, pub


def _user_block(pub: str, pubs: list[str], subs: list[str]) -> str:
    """Render one nats.conf user entry with deny-by-default permissions."""
    pub_list = "\n".join(f"        {p!r}," for p in pubs)
    sub_list = "\n".join(f"        {s!r}," for s in subs)
    return (
        "    {\n"
        f"      nkey: {pub!r}\n"
        "      permissions: {\n"
        "        publish: [" + pub_list + "\n        ]\n"
        "        subscribe: [" + sub_list + "\n        ]\n"
        "      }\n"
        "    },"
    )


_ORCH_PUB = [
    "mesh.>",  # the orchestrator drives the protocol subjects
    "$JS.>",
]
_ORCH_SUB = [
    "mesh.>",
    "mem.>",
    "$KV.>",
    "_INBOX.>",
]


def _node_pubs(node: str) -> list[str]:
    # Worker egress, deny-by-default beyond this. Dynamic ids (task_id,
    # step_id) cannot be baked into a static config, so the worker gets
    # narrowly-wildcarded subjects instead of the blanket `mesh.>` the
    # shared token implied; per-task isolation is a M7/account-level follow-up.
    return [
        f"mesh.node.{node}.>",  # own heartbeat + node telemetry
        "mesh.task.*.events",  # append to task event streams
        "mesh.agent.*.result",  # role results (role is payload, not transport)
        "mesh.bid.*.*",  # SUBJECT_BID = mesh.bid.{task_id}.{step_id}
        "mesh.ledger",  # M11 claim CAS
        "mesh.registry.register",
        "mesh.registry.withdraw",
        "mesh.model.decision",  # T-pull votes
        "mem.agent.*.work",  # agent inbox replies (agent_id unknown at config time)
        "$JS.>",  # JetStream API calls
        "$KV.*.>",  # KV publishes go to $KV.<bucket>.<key>, not $JS.API
    ]


def _node_subs(node: str) -> list[str]:
    return [
        "mesh.task.>",  # tasks are broadcast/fan-out to all workers
        "mesh.agent.*.cmd",
        "mesh.auction.*.*",
        f"mesh.node.{node}.>",
        "mem.agent.*.work",
        "$KV.>",
        "_INBOX.>",
    ]


def generate_config(
    orchestrator: str, nodes: list[str], secrets_dir: Path, rotate: bool = False
) -> Path:
    """Write nats.conf into secrets_dir; return its path."""
    secrets_dir.mkdir(parents=True, exist_ok=True)
    entries: list[str] = []

    _, orch_pub = _generate_user_nkey(secrets_dir, orchestrator, rotate)
    entries.append(_user_block(orch_pub, _ORCH_PUB, _ORCH_SUB))
    for node in nodes:
        _, pub = _generate_user_nkey(secrets_dir, node, rotate)
        entries.append(_user_block(pub, _node_pubs(node), _node_subs(node)))
    # Trim the trailing comma off the last entry.
    entries[-1] = entries[-1].rstrip(",")

    conf = (
        "# GENERATED by scripts/gen_nkeys.py — do not edit by hand.\n"
        "# Per-node NKey users (H4): deny-by-default, subject scopes follow\n"
        "# the subject map in src/memnc/schema.py. Never commit this file.\n"
        "listen: 0.0.0.0:4222\n"
        # 0.0.0.0 on purpose: in docker the host-side port mapping
        # (127.0.0.1:8222:8222) is the loopback restriction; binding the
        # container-internal loopback here would break the mapping.
        "http: 0.0.0.0:8222\n"
        "jetstream: {\n"
        "  store_dir: /data\n"
        "}\n"
        "authorization: {\n"
        "  users: [\n" + "\n".join(entries) + "\n  ]\n"
        "}\n"
    )
    conf_path = secrets_dir / "nats.conf"
    conf_path.write_text(conf)
    os.chmod(conf_path, stat.S_IRUSR | stat.S_IWUSR)  # 0600: holds no secrets
    print(f"wrote {conf_path}")
    return conf_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--orchestrator", required=True, help="orchestrator user id")
    parser.add_argument("--nodes", nargs="+", required=True, help="node user ids")
    parser.add_argument(
        "--secrets-dir", default="secrets", type=Path, help="output dir (default: secrets/)"
    )
    parser.add_argument(
        "--rotate", action="store_true", help="regenerate even existing keys (invalidates old ones)"
    )
    args = parser.parse_args()
    generate_config(args.orchestrator, args.nodes, args.secrets_dir, args.rotate)


if __name__ == "__main__":
    main()
